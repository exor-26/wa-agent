test('offline owner outreach persists and sends after reconnect without another contact message', async t => {
  const { store, agent, transport, external } = setup(t)
  const contact = store.contact('1001@lid')
  transport.ready = false
  const reply = await agent.command(`/reply ${contact.id} Hello from Aditya`)
  assert.match(reply, /Queued/)
  assert.equal(external.length, 0)
  assert.equal(store.data.settings.ownerLastAction.status, 'queued')
  const restored = new Store(store.file)
  const queue = new Outbox({ store: restored, ready: () => true, send: transport.sendContact })
  t.after(() => queue.stop())
  await queue.drain(); await queue.drain()
  assert.equal(external.length, 1)
  assert.equal(restored.data.outreach[0].status, 'accepted_by_transport')
})
