const decision = extra => ({ reply: null, claim: null, concern: null, actions: [], facts: [], photo_summary: null,
  draft: null, activity_summary: null, instruction_updates: [], outreach: [], ...extra })
const action = (type, target, text, extra = {}) => ({ type, target, text, name: null, relationship: null, permission: null, model: null, ...extra })
function setup(t, generate = async () => decision()) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'clara-outreach-'))
  const store = new Store(path.join(root, 'state.json'))
  const external = [], owner = []
  const transport = { ready: true, sendContact: async (contact, text) => {
    external.push({ contact: contact.id, text }); return { key: { id: `sent-${external.length}` } }
  }, sendOwner: async text => { owner.push(text); return { key: { id: `owner-${owner.length}` } } } }
  const agent = new Agent({ store, transport, provider: { generate }, config: { takeoverMs: 14000 },
    profile: { owner: 'Aditya', timezone: 'Asia/Kolkata', public: {}, schedule: { weekday: [], weekend: [] } } })
  t.after(() => { agent.stop(); fs.rmSync(root, { recursive: true, force: true }) })
  return { root, store, transport, agent, external, owner }
}
const settle = async () => { for (let i = 0; i < 20; i++) await Promise.resolve() }

test('exact brother exchange saves, confirms and sends the inline UPI using the notified thread', async t => {
  let selected
  const { store, agent, external, owner } = setup(t, async context => {
    selected = context.recipientResolution.selectedContact
    return decision({ facts: [{ text: 'Aditya UPI is demo@ybl.', kind: 'personal' }], actions: [
      action('send', selected, 'demo@ybl'), action('approve', selected, null, { relationship: 'brother', permission: 'public' })
    ] })
  })
  const old = store.contact('1001@lid'), current = store.contact('1002@lid')
  for (const contact of [old, current]) store.applyNames(contact, { saved: 'Bhai' })
  store.data.settings.ownerFocus = { contacts: [old.id], at: Date.now() - FOCUS_TTL_MS - 1000 }
  store.append(current.id, 'user', 'QR ya UPI id de; 5000 mangwana hai')
  const concern = store.concern(current, 'Needs the owner UPI ID')
  await agent.relayConcern(concern)
  await agent.receiveOwner('demo@ybl is my UPI ID, he is my brother, send it and save this UPI', null, null, { requestKey: 'owner-upi' })
  assert.equal(selected, current.id)
  assert.deepEqual(external, [{ contact: current.id, text: 'demo@ybl' }])
  assert.equal(current.confirmed, true)
  assert.equal(current.permission, 'public')
  assert.equal(store.data.facts.length, 1)
  assert.match(owner.at(-1), /Saved F0001/)
  assert.match(owner.at(-1), /Sent to Bhai/)
  assert.equal(agent.context(current).personal, null)
  assert.equal(agent.context(current).sharedOwnerFacts[0].id, 'F0001')
  assert.equal(agent.context(old).sharedOwnerFacts.length, 0)
})
