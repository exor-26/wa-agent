const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { installSafeConsole, sanitizeLog } = require('../src/logging')

test('console filters session objects and embedded private-key dumps but keeps useful logs', () => {
  const output = []
  const target = Object.fromEntries(['log', 'info', 'warn', 'error', 'debug'].map(method => [method, (...args) => output.push(args)]))
  const restore = installSafeConsole(target)
  target.info('Closing session:', { currentRatchet: { privKey: 'synthetic-secret' } })
  target.warn('Debug', { nested: { rootKey: 'another-synthetic-secret' } })
  target.log('{"privKey": "embedded-synthetic-secret"}')
  target.error('Connection temporarily unavailable')
  target.log('[2026-10-23T18:00:00.000Z] SERVICE_READY {}')
  restore()
  const text = JSON.stringify(output)
  assert.doesNotMatch(text, /synthetic-secret|privKey|rootKey/)
  assert.match(text, /Connection temporarily unavailable|SERVICE_READY/)
  assert.equal(output.filter(args => args[0] === '[SESSION_DEBUG_REDACTED]').length, 3)
})

test('existing logs lose multiline session internals while structured event evidence stays private', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'clara-logs-'))
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
  const file = path.join(dir, 'clara.log')
  fs.writeFileSync(file, '[2026-10-23T18:00:00.000Z] SERVICE_READY {}\nClosing session: SessionEntry {\n privKey: synthetic-secret\n rootKey: more-secret\n}\n[2026-10-23T18:01:00.000Z] REPLY_SENT {"contact":"C0001"}\n')
  sanitizeLog(file)
  const text = fs.readFileSync(file, 'utf8')
  assert.doesNotMatch(text, /synthetic-secret|more-secret|SessionEntry/)
  assert.match(text, /SERVICE_READY/)
  assert.match(text, /REPLY_SENT/)
  assert.match(text, /LOG_SANITIZED/)
  assert.equal(fs.statSync(file).mode & 0o777, 0o600)
})
